def build():
    market_by_name = {m[0]: m for m in MARKETS}
    for name, (address, lat, lng) in EXISTING_MARKETS.items():
        market_by_name.setdefault(name, (name, address, lat, lng, "", "", ""))
    data = {"markets": [], "merchants": [], "products": [],
            "market_updates": [], "merchant_updates": []}

    for i, (name, address, lat, lng, intro, slug, query) in enumerate(MARKETS, 1):
        data["markets"].append({
            "name": name, "province": CITY[0], "city": CITY[1],
            "address": address, "lat": lat, "lng": lng, "intro": intro,
            "sort": i, "file": "markets/%s.jpg" % slug, "query": query, "mode": "shop",
        })

    phone = 13800138100
    for name, market, category, slug, query, intro, products in MERCHANTS:
        phone += 1
        m = market_by_name[market]
        data["merchants"].append({
            "name": name, "market": market, "category": category,
            "contact": "门店经理", "phone": str(phone),
            "province": CITY[0], "city": CITY[1],
            "address": m[1], "lat": round(m[2] + 0.0004, 6), "lng": round(m[3] + 0.0004, 6),
            "intro": intro, "file": "merchants/%s.jpg" % slug, "query": query, "mode": "shop",
        })
        for n, (pname, brand, origin, spec, ptype, price, unit, desc, pquery) in enumerate(products, 1):
            data["products"].append({
                "merchant": name, "category": category, "name": pname, "brand": brand,
                "origin": origin, "spec": spec, "typeName": ptype, "price": price,
                "unit": unit, "description": desc,
                "file": "products/%s-%d.jpg" % (slug, n), "query": pquery, "mode": "product",
            })

    for name, slug, query in UPDATE_MARKETS:
        data["market_updates"].append({
            "name": name, "file": "markets/%s.jpg" % slug, "query": query, "mode": "shop",
        })
    for name, slug, query in UPDATE_MERCHANTS:
        data["merchant_updates"].append({
            "name": name, "file": "merchants/%s.jpg" % slug, "query": query, "mode": "shop",
        })

    with open("data.json", "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print("markets", len(data["markets"]), "merchants", len(data["merchants"]),
          "products", len(data["products"]), "market_updates", len(data["market_updates"]),
          "merchant_updates", len(data["merchant_updates"]))


if __name__ == "__main__":
    build()
